/*
 * z380term - tiny framebuffer terminal + pty relay for the ASUS Z380M (MT8163, mtkfb).
 *
 * Runs a command (default /bin/sh) on a proper pty so job control and Ctrl-C work,
 * mirrors everything it prints to the tablet screen (/dev/fb0) and to a USB serial
 * line (/dev/ttyGS*), and feeds bytes typed on the serial line to the command.
 *
 * usage: z380term [-n] [-f /dev/fb0] [-s /dev/ttyGS0] [--] [command args...]
 *
 *   -n   do not swap red and blue. By default z380term swaps the red and blue
 *        channel positions the driver reports, because on the Z380M (mtkfb)
 *        the reported var offsets come out with red and blue exchanged on the
 *        panel (confirmed on the tablet screen). The banner prints both the
 *        reported and the used positions.
 *
 * Built-in 8x16 font: koi8x16 (X11 cyrillic fonts, public domain).
 */
