/* ---- framebuffer ---- */
static int fbfd = -1, xres = 800, yres = 1280;
static uint32_t line_len = 3200;
static uint8_t *fbmem = NULL;
static size_t yoff_bytes = 0;
static uint32_t *shadow = NULL;
static int roff = 16, goff = 8, boff = 0, aoff = 24;
static int rlen = 8, glen = 8, blen = 8, alen = 8;
static int swaprb = 1;                       /* -n clears it */
static int raw_roff = 16, raw_boff = 0;      /* as reported by the driver, for the banner */
static uint32_t pk[16];

static uint32_t pack(int r, int g, int b)
{
	uint32_t v = ((uint32_t)(r >> (8 - rlen)) << roff) |
		     ((uint32_t)(g >> (8 - glen)) << goff) |
		     ((uint32_t)(b >> (8 - blen)) << boff);
	if (alen)
		v |= (((1u << alen) - 1) << aoff);
	return v;
}

/* ---- terminal state ---- */
typedef struct { uint8_t ch, fg, bg; } cell_t;
static cell_t *cells;
static uint8_t *dirty;
static int cols, rows, cx, cy, cur_fg = 7, cur_bg = 0, bold, rev;
static int saved_x, saved_y, full_dirty = 1, last_cx = -1, last_cy = -1;
static int st, par[8], npar, priv;
static char fbinfo[256];

static void clear_range(int r, int c0, int c1)
{
	for (int c = c0; c < c1; c++) {
		cell_t *k = &cells[r * cols + c];
		k->ch = ' '; k->fg = 7; k->bg = 0;
	}
	dirty[r] = 1;
}

static void scroll_up(void)
{
	memmove(cells, cells + cols, (size_t)(rows - 1) * cols * sizeof(cell_t));
	clear_range(rows - 1, 0, cols);
	full_dirty = 1;
}

static void newline(void)
{
	if (cy >= rows - 1)
		scroll_up();
	else
		cy++;
}

static void put_printable(uint8_t ch)
{
	if (cx >= cols) { cx = 0; newline(); }
	cell_t *k = &cells[cy * cols + cx];
	int fg = cur_fg, bg = cur_bg;
	if (bold && fg < 8) fg += 8;
	if (rev) { int t = fg; fg = bg; bg = t; }
	k->ch = ch; k->fg = fg; k->bg = bg;
	dirty[cy] = 1;
	cx++;
}

static void sgr(void)
{
	int n = npar ? npar : 1;
	for (int i = 0; i < n; i++) {
		int p = par[i];
		if (p == 0) { cur_fg = 7; cur_bg = 0; bold = 0; rev = 0; }
		else if (p == 1) bold = 1;
		else if (p == 22) bold = 0;
		else if (p == 7) rev = 1;
		else if (p == 27) rev = 0;
		else if (p >= 30 && p <= 37) cur_fg = p - 30;
		else if (p == 39) cur_fg = 7;
		else if (p >= 40 && p <= 47) cur_bg = p - 40;
		else if (p == 49) cur_bg = 0;
		else if (p >= 90 && p <= 97) cur_fg = p - 90 + 8;
		else if (p >= 100 && p <= 107) cur_bg = p - 100;
	}
}

static int clampi(int v, int lo, int hi) { return v < lo ? lo : (v > hi ? hi : v); }

static void csi(uint8_t c)
{
	int n1 = par[0] ? par[0] : 1;
	if (priv) return;
	switch (c) {
	case 'A': cy = clampi(cy - n1, 0, rows - 1); break;
	case 'B': cy = clampi(cy + n1, 0, rows - 1); break;
	case 'C': cx = clampi(cx + n1, 0, cols - 1); break;
	case 'D': cx = clampi(cx - n1, 0, cols - 1); break;
	case 'G': cx = clampi(n1 - 1, 0, cols - 1); break;
	case 'd': cy = clampi(n1 - 1, 0, rows - 1); break;
	case 'H': case 'f':
		cy = clampi(n1 - 1, 0, rows - 1);
		cx = clampi((npar > 1 && par[1] ? par[1] : 1) - 1, 0, cols - 1);
		break;
	case 'J':
		if (par[0] == 0) { clear_range(cy, cx < cols ? cx : cols, cols); for (int r = cy + 1; r < rows; r++) clear_range(r, 0, cols); }
		else if (par[0] == 1) { for (int r = 0; r < cy; r++) clear_range(r, 0, cols); clear_range(cy, 0, cx < cols ? cx + 1 : cols); }
		else { for (int r = 0; r < rows; r++) clear_range(r, 0, cols); }
		break;
	case 'K':
		if (par[0] == 0) clear_range(cy, cx < cols ? cx : cols, cols);
		else if (par[0] == 1) clear_range(cy, 0, cx < cols ? cx + 1 : cols);
		else clear_range(cy, 0, cols);
		break;
	case 'P': {
		int x = cx < cols ? cx : cols - 1, n = clampi(n1, 0, cols - x);
		cell_t *row = &cells[cy * cols];
		memmove(row + x, row + x + n, (size_t)(cols - x - n) * sizeof(cell_t));
		clear_range(cy, cols - n, cols);
		break; }
	case '@': {
		int x = cx < cols ? cx : cols - 1, n = clampi(n1, 0, cols - x);
		cell_t *row = &cells[cy * cols];
		memmove(row + x + n, row + x, (size_t)(cols - x - n) * sizeof(cell_t));
		clear_range(cy, x, x + n);
		break; }
	case 'X': { int x = cx < cols ? cx : cols - 1; clear_range(cy, x, clampi(x + n1, 0, cols)); break; }
	case 'L': {
		int n = clampi(n1, 0, rows - cy);
		memmove(&cells[(cy + n) * cols], &cells[cy * cols], (size_t)(rows - cy - n) * cols * sizeof(cell_t));
		for (int r = cy; r < cy + n; r++) clear_range(r, 0, cols);
		full_dirty = 1; break; }
	case 'M': {
		int n = clampi(n1, 0, rows - cy);
		memmove(&cells[cy * cols], &cells[(cy + n) * cols], (size_t)(rows - cy - n) * cols * sizeof(cell_t));
		for (int r = rows - n; r < rows; r++) clear_range(r, 0, cols);
		full_dirty = 1; break; }
	case 'm': sgr(); break;
	case 's': saved_x = cx; saved_y = cy; break;
	case 'u': cx = saved_x; cy = saved_y; break;
	default: break;
	}
}

static void term_putc(uint8_t c)
{
	switch (st) {
	case 0:
		if (c == 0x1b) { st = 1; return; }
		if (c == '\n' || c == 0x0b || c == 0x0c) { newline(); return; }
		if (c == '\r') { cx = 0; return; }
		if (c == '\b') { if (cx >= cols) cx = cols - 1; if (cx > 0) cx--; return; }
		if (c == '\t') { cx = (cx + 8) & ~7; if (cx >= cols) cx = cols - 1; return; }
		if (c < 32 || c == 0x7f) return;
		put_printable(c);
		return;
	case 1:
		if (c == '[') { st = 2; npar = 0; priv = 0; memset(par, 0, sizeof par); return; }
		if (c == '(' || c == ')') { st = 3; return; }
		if (c == '7') { saved_x = cx; saved_y = cy; }
		else if (c == '8') { cx = saved_x; cy = saved_y; }
		else if (c == 'M') { if (cy > 0) cy--; }
		st = 0;
		return;
	case 2:
		if (c >= '0' && c <= '9') { if (!npar) npar = 1; par[npar - 1] = par[npar - 1] * 10 + (c - '0'); return; }
		if (c == ';') { if (!npar) npar = 1; if (npar < 8) npar++; return; }
		if (c == '?' || c == '>' || c == '!' || c == '=') { priv = 1; return; }
		if (c >= 0x20 && c <= 0x2f) return;
		if (c >= 0x40 && c <= 0x7e) { csi(c); st = 0; return; }
		st = 0;
		return;
	default:
		st = 0;
		return;
	}
}

static void term_write(const uint8_t *b, size_t n)
{
	for (size_t i = 0; i < n; i++) term_putc(b[i]);
}

static void term_puts(const char *s) { term_write((const uint8_t *)s, strlen(s)); }

static void draw_cell(int r, int c)
{
	cell_t *k = &cells[r * cols + c];
	uint32_t fg = pk[k->fg & 15], bg = pk[k->bg & 15];
	if (r == (cy) && c == (cx >= cols ? cols - 1 : cx)) { uint32_t t = fg; fg = bg; bg = t; }
	const uint8_t *g = font8x16[k->ch];
	for (int y = 0; y < FH; y++) {
		uint32_t *d = shadow + (size_t)(r * FH + y) * xres + c * FW;
		uint8_t bits = g[y];
		for (int x = 0; x < FW; x++)
			d[x] = (bits & (0x80 >> x)) ? fg : bg;
	}
}

static void flush(void)
{
	int ccx = cx >= cols ? cols - 1 : cx;
	if (last_cy >= 0 && last_cy < rows) dirty[last_cy] = 1;
	if (cy < rows) dirty[cy] = 1;
	for (int r = 0; r < rows; r++) {
		if (!full_dirty && !dirty[r]) continue;
		for (int c = 0; c < cols; c++) draw_cell(r, c);
		if (fbmem)
			for (int y = 0; y < FH; y++)
				memcpy(fbmem + yoff_bytes + (size_t)(r * FH + y) * line_len,
				       shadow + (size_t)(r * FH + y) * xres, (size_t)xres * 4);
		dirty[r] = 0;
	}
	full_dirty = 0;
	last_cx = ccx; last_cy = cy;
}

static void fb_init(const char *path)
{
	struct fb_var_screeninfo v;
	struct fb_fix_screeninfo f;
	size_t maplen;

	fbfd = open(path, O_RDWR | O_CLOEXEC);
	if (fbfd < 0) { fprintf(stderr, "z380term: cannot open %s: %s\n", path, strerror(errno)); return; }
	if (ioctl(fbfd, FBIOGET_VSCREENINFO, &v) == 0) {
		xres = v.xres; yres = v.yres;
		if (v.blue.length || v.green.length || v.red.length) {
			roff = v.red.offset; rlen = v.red.length ? v.red.length : 8;
			goff = v.green.offset; glen = v.green.length ? v.green.length : 8;
			boff = v.blue.offset; blen = v.blue.length ? v.blue.length : 8;
			aoff = v.transp.offset; alen = v.transp.length;
		}
		if (v.bits_per_pixel != 32)
			fprintf(stderr, "z380term: warning: bpp=%u (only 32 supported)\n", v.bits_per_pixel);
		raw_roff = roff; raw_boff = boff;
		if (swaprb) {
			int t = roff; roff = boff; boff = t;
			t = rlen; rlen = blen; blen = t;
		}
		snprintf(fbinfo, sizeof fbinfo,
			 "fb %dx%d bpp=%u reported R@%d G@%d B@%d A@%d/%d yoff=%u; used R@%d B@%d swaprb=%d",
			 xres, yres, v.bits_per_pixel, raw_roff, goff, raw_boff, aoff, alen, v.yoffset,
			 roff, boff, swaprb);
		line_len = xres * 4;
		if (ioctl(fbfd, FBIOGET_FSCREENINFO, &f) == 0 && f.line_length)
			line_len = f.line_length;
		yoff_bytes = (size_t)v.yoffset * line_len;
		maplen = (size_t)line_len * (v.yres_virtual ? (size_t)v.yres_virtual : (size_t)yres);
		if (ioctl(fbfd, FBIOGET_FSCREENINFO, &f) == 0 && f.smem_len && f.smem_len < maplen)
			maplen = f.smem_len;
	} else {
		raw_roff = roff; raw_boff = boff;
		if (swaprb) {
			int t = roff; roff = boff; boff = t;
			t = rlen; rlen = blen; blen = t;
		}
		snprintf(fbinfo, sizeof fbinfo, "fb (no ioctl) %dx%d assumed R@%d B@%d swaprb=%d",
			 xres, yres, roff, boff, swaprb);
		line_len = xres * 4;
		maplen = (size_t)line_len * yres;
	}
	fbmem = mmap(NULL, maplen, PROT_READ | PROT_WRITE, MAP_SHARED, fbfd, 0);
	if (fbmem == MAP_FAILED) {
		fprintf(stderr, "z380term: mmap failed: %s\n", strerror(errno));
		fbmem = NULL;
	}
}

static void term_init(void)
{
	cols = xres / FW; rows = yres / FH;
	cells = calloc((size_t)cols * rows, sizeof(cell_t));
	dirty = calloc(rows, 1);
	shadow = malloc((size_t)xres * yres * 4);
	if (!cells || !dirty || !shadow) { fprintf(stderr, "z380term: out of memory\n"); exit(1); }
	for (int i = 0; i < 16; i++) pk[i] = pack(pal[i][0], pal[i][1], pal[i][2]);
	for (size_t i = 0; i < (size_t)xres * yres; i++) shadow[i] = pk[0];
	for (int r = 0; r < rows; r++) clear_range(r, 0, cols);
	full_dirty = 1;
}

static void banner(void)
{
	struct utsname u;
	char line[400];
	uname(&u);
	snprintf(line, sizeof line, "z380term - %s %s %s\r\n", u.sysname, u.release, u.machine);
	term_puts("\x1b[1;32m"); term_puts(line); term_puts("\x1b[0m");
	term_puts(z380m_credit_term); term_puts("\r\n");
	snprintf(line, sizeof line, "%s  text %dx%d\r\n", fbinfo, cols, rows);
	term_puts(line);
	term_puts("colour test: \x1b[41m RED \x1b[42m GREEN \x1b[44m BLUE \x1b[47m\x1b[30m WHITE \x1b[0m\r\n");
	term_puts("ABCDEFGHIJKLMNOPQRSTUVWXYZ abcdefghijklmnopqrstuvwxyz 0123456789\r\n");
	term_puts("!\"#$%&'()*+,-./:;<=>?@[\\]^_`{|}~\r\n\r\n");
	flush();
}

/* ---- serial / pty plumbing ---- */
static int open_serial(const char *path)
{
	int fd = open(path, O_RDWR | O_NOCTTY | O_NONBLOCK | O_CLOEXEC);
	if (fd < 0) return -1;
	struct termios t;
	if (tcgetattr(fd, &t) == 0) {
		cfmakeraw(&t);
		t.c_cc[VMIN] = 1; t.c_cc[VTIME] = 0;
		tcsetattr(fd, TCSANOW, &t);
	}
	return fd;
}

static void write_all(int fd, const uint8_t *b, size_t n, int tries)
{
	while (n > 0 && tries-- > 0) {
		ssize_t w = write(fd, b, n);
		if (w > 0) { b += w; n -= (size_t)w; continue; }
		if (w < 0 && errno == EINTR) continue;
		if (w < 0 && errno == EAGAIN) {
			struct pollfd p = { fd, POLLOUT, 0 };
			poll(&p, 1, 50);
			continue;
		}
		return;
	}
}

static pid_t spawn(char **cmd, int *mfd)
{
	int m = posix_openpt(O_RDWR | O_NOCTTY | O_CLOEXEC);
	if (m < 0) { fprintf(stderr, "z380term: posix_openpt: %s\n", strerror(errno)); return -1; }
	if (grantpt(m) < 0 || unlockpt(m) < 0) { fprintf(stderr, "z380term: grantpt/unlockpt: %s\n", strerror(errno)); close(m); return -1; }
	char *sn = ptsname(m);
	if (!sn) { fprintf(stderr, "z380term: ptsname: %s\n", strerror(errno)); close(m); return -1; }
	char slave[128];
	snprintf(slave, sizeof slave, "%s", sn);
	struct winsize ws = { (unsigned short)rows, (unsigned short)cols, 0, 0 };
	ioctl(m, TIOCSWINSZ, &ws);
	pid_t pid = fork();
	if (pid < 0) { close(m); return -1; }
	if (pid == 0) {
		setsid();
		int s = open(slave, O_RDWR);
		if (s < 0) _exit(126);
		ioctl(s, TIOCSCTTY, 0);
		dup2(s, 0); dup2(s, 1); dup2(s, 2);
		if (s > 2) close(s);
		signal(SIGPIPE, SIG_DFL); signal(SIGHUP, SIG_DFL);
		setenv("TERM", "linux", 1);
		execvp(cmd[0], cmd);
		_exit(127);
	}
	fcntl(m, F_SETFL, fcntl(m, F_GETFL) | O_NONBLOCK);
	*mfd = m;
	return pid;
}

int main(int argc, char **argv)
{
	const char *fbpath = "/dev/fb0", *serpath = NULL;
	static char *defcmd[] = { "/bin/sh", NULL };
	int i = 1;
	for (; i < argc; i++) {
		if (!strcmp(argv[i], "-n")) swaprb = 0;
		else if (!strcmp(argv[i], "-f") && i + 1 < argc) fbpath = argv[++i];
		else if (!strcmp(argv[i], "-s") && i + 1 < argc) serpath = argv[++i];
		else if (!strcmp(argv[i], "--")) { i++; break; }
		else break;
	}
	char **cmd = (i < argc) ? &argv[i] : defcmd;

	signal(SIGPIPE, SIG_IGN);
	signal(SIGHUP, SIG_IGN);
	fb_init(fbpath);
	term_init();
	banner();

	int ser = serpath ? open_serial(serpath) : -1;
	time_t last_try = time(NULL);
	int master = -1;
	pid_t pid = spawn(cmd, &master);
	time_t started = time(NULL);
	if (pid < 0) { term_puts("\x1b[1;31mz380term: cannot start shell (pty)\x1b[0m\r\n"); flush(); return 2; }

	uint8_t buf[4096];
	for (;;) {
		struct pollfd p[2];
		int n = 0;
		p[n++] = (struct pollfd){ master, POLLIN, 0 };
		if (ser >= 0) p[n++] = (struct pollfd){ ser, POLLIN, 0 };
		int r = poll(p, n, 500);
		if (r > 0) {
			if (p[0].revents & POLLIN) {
				ssize_t k = read(master, buf, sizeof buf);
				if (k > 0) {
					if (ser >= 0) write_all(ser, buf, (size_t)k, 4);
					term_write(buf, (size_t)k);
					flush();
				}
			}
			if (ser >= 0 && n == 2) {
				if (p[1].revents & POLLIN) {
					ssize_t k = read(ser, buf, sizeof buf);
					if (k > 0) write_all(master, buf, (size_t)k, 20);
					else if (k == 0 || (k < 0 && errno != EAGAIN && errno != EINTR)) { close(ser); ser = -1; }
				} else if (p[1].revents & (POLLHUP | POLLERR | POLLNVAL)) {
					close(ser); ser = -1;
				}
			}
		}
		int status;
		if (waitpid(pid, &status, WNOHANG) == pid) {
			ssize_t k;
			while ((k = read(master, buf, sizeof buf)) > 0) {
				if (ser >= 0) write_all(ser, buf, (size_t)k, 4);
				term_write(buf, (size_t)k);
			}
			close(master);
			snprintf((char *)buf, sizeof buf, "\r\n[command exited, status %d - restarting]\r\n",
				 WIFEXITED(status) ? WEXITSTATUS(status) : -1);
			if (ser >= 0) write_all(ser, buf, strlen((char *)buf), 4);
			term_write(buf, strlen((char *)buf));
			flush();
			if (time(NULL) - started < 2) sleep(2);
			pid = spawn(cmd, &master);
			started = time(NULL);
			if (pid < 0) { term_puts("z380term: respawn failed\r\n"); flush(); return 2; }
		}
		if (ser < 0 && serpath && time(NULL) - last_try >= 1) {
			last_try = time(NULL);
			ser = open_serial(serpath);
		}
	}
}
